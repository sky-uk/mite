"""Convert a browser HAR recording into a runnable mite journey and scenario."""

import json
import logging
import re
from collections import Counter
from dataclasses import dataclass, field
from datetime import datetime
from fnmatch import fnmatch
from pathlib import Path
from urllib.parse import parse_qsl, quote, urlsplit

from jinja2 import Template

logger = logging.getLogger(__name__)

# Methods available on mite_browser.Browser
SUPPORTED_METHODS = {"get", "post", "put", "patch", "delete", "head", "options"}

# Chrome's _resourceType values that are page assets or browser-generated
# (CORS preflight) rather than application calls
STATIC_RESOURCE_TYPES = {
    "preflight",
    "image",
    "font",
    "stylesheet",
    "script",
    "media",
    "manifest",
    "texttrack",
}
# Fallback for HARs without _resourceType
STATIC_MIME_PREFIXES = (
    "image/",
    "font/",
    "audio/",
    "video/",
    "text/css",
    "text/javascript",
    "application/javascript",
    "application/x-javascript",
)

# Content-Length is recomputed for the replayed body; the browser session
# manages cookies itself
DROPPED_HEADERS = {"cookie", "content-length"}
SENSITIVE_HEADERS = {"authorization", "proxy-authorization"}
SENSITIVE_NAME_PARTS = (
    "token",
    "auth",
    "secret",
    "session",
    "password",
    "passwd",
    "apikey",
    "api-key",
    "api_key",
)
SENSITIVE_BODY_KEY_PARTS = SENSITIVE_NAME_PARTS + ("email",)
EMAIL_RE = re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+")
# Shorter values ("true", "stream") are too likely to appear elsewhere by
# coincidence, and every occurrence is replaced; emails are always kept
MIN_SECRET_LENGTH = 8

# Values are pre-rendered as Python expressions so HAR data stays valid Python
TEMPLATE = Template(
    "    async with ensure_fixed_separation({{separation}}):\n"
    "        async with ctx.transaction({{name}}):\n"
    "            resp = await ctx.browser.{{method}}(\n"
    "                {{url}},\n"
    "                headers={{headers}},\n"
    "{{body}}"
    "            )\n"
    "            check_status_code(resp, {{expected_status}})\n"
    "\n",
    keep_trailing_newline=True,
)


class HarConversionError(Exception):
    """The HAR can't be converted as requested; the message tells the user what to do."""


def set_expected_status_code(cur_page, entries):
    code = cur_page["response"]["status"]
    # The HTTP client follows redirects, so expect the status of the final page
    if 300 <= code < 400 and code != 304 and cur_page["response"]["redirectURL"]:
        for other_page in entries:
            if cur_page["response"]["redirectURL"] == other_page["request"]["url"]:
                cur_page["response"]["redirectURL"] = other_page["response"][
                    "redirectURL"
                ]
                cur_page["response"]["status"] = other_page["response"]["status"]
                entries.remove(other_page)
                return set_expected_status_code(cur_page, entries)
    elif code == 304:
        # a recorded 304 depends on browser cache state; a replay may get 200
        code = (200, 304)
    return code


def set_request_headers_dict(page):
    # ":"-prefixed names are HTTP/2 pseudo-headers, generated by the client
    return {
        header["name"]: header["value"]
        for header in page["request"]["headers"]
        if header["name"].lower() not in DROPPED_HEADERS
        and not header["name"].startswith(":")
    }


def _extract_and_sort_requests(pages):
    """Pull entries from har text and sort into chronological order"""
    entries = pages["log"]["entries"]
    entries.sort(key=lambda n: n["startedDateTime"])
    return entries


def _started_at(entry):
    return datetime.fromisoformat(entry["startedDateTime"])


def _netloc(url):
    return urlsplit(url).netloc.lower()


def host_allowed(url, patterns):
    """True if the URL's host (with or without port) matches a glob pattern."""
    parts = urlsplit(url)
    candidates = {parts.netloc.lower(), (parts.hostname or "").lower()}
    return any(fnmatch(c, p.lower()) for c in candidates for p in patterns)


def is_static(entry):
    resource_type = entry.get("_resourceType")
    if resource_type is not None:
        return resource_type in STATIC_RESOURCE_TYPES
    mime = entry["response"].get("content", {}).get("mimeType", "").lower()
    return mime.startswith(STATIC_MIME_PREFIXES)


def is_sensitive_name(name, parts=SENSITIVE_NAME_PARTS):
    name = name.lower()
    return name in SENSITIVE_HEADERS or any(part in name for part in parts)


def _slug(name):
    return re.sub(r"[^0-9a-z]+", "_", name.lower()).strip("_") or "value"


@dataclass
class Secrets:
    """Maps values seen in the recording to config keys used in the script."""

    keys: dict = field(default_factory=dict)  # value -> key

    def add(self, name, value):
        if not isinstance(value, str):
            return
        if len(value) < MIN_SECRET_LENGTH and not EMAIL_RE.fullmatch(value):
            return
        if value in self.keys:
            return
        base = _slug(name)
        key = base
        n = 2
        while key in self.keys.values():
            key = f"{base}_{n}"
            n += 1
        self.keys[value] = key

    def _pattern(self):
        forms = {}
        for value, key in self.keys.items():
            forms[value] = (key, False)
            encoded = quote(value, safe="")
            if encoded != value:
                forms.setdefault(encoded, (key, True))
        # longest first so a value is not split by a shorter one inside it
        ordered = sorted(forms, key=len, reverse=True)
        return re.compile("|".join(re.escape(f) for f in ordered)), forms

    def expression(self, text):
        """Python expression for ``text`` with each secret read from config."""
        if not self.keys:
            return repr(text)
        pattern, forms = self._pattern()
        parts = []
        pos = 0
        for match in pattern.finditer(text):
            if match.start() > pos:
                parts.append(repr(text[pos : match.start()]))
            key, encoded = forms[match.group()]
            lookup = f"_config(ctx, {key!r})"
            parts.append(f'quote({lookup}, safe="")' if encoded else lookup)
            pos = match.end()
        if pos < len(text) or not parts:
            parts.append(repr(text[pos:]))
        return " + ".join(parts)

    def redact(self, text):
        """``text`` with each secret shown as ``<key>``, for comments and names."""
        if not self.keys:
            return text
        pattern, forms = self._pattern()
        return pattern.sub(lambda m: f"<{forms[m.group()][0]}>", text)

    def uses_quote(self, texts):
        if not self.keys:
            return False
        pattern, forms = self._pattern()
        return any(
            forms[m.group()][1] for text in texts for m in pattern.finditer(text)
        )


def _collect_json_secrets(value, secrets, key=None):
    if isinstance(value, dict):
        for k, v in value.items():
            _collect_json_secrets(v, secrets, k)
    elif isinstance(value, list):
        for v in value:
            _collect_json_secrets(v, secrets, key)
    elif isinstance(value, str) and key and is_sensitive_name(
        key, SENSITIVE_BODY_KEY_PARTS
    ):
        secrets.add(key, value)


def collect_secrets(requests):
    secrets = Secrets()
    for request in requests:
        for name, value in request.headers.items():
            if is_sensitive_name(name):
                secrets.add(name, value)
        for name, value in parse_qsl(urlsplit(request.url).query):
            if is_sensitive_name(name, SENSITIVE_BODY_KEY_PARTS):
                secrets.add(name, value)
        if request.body is not None:
            try:
                _collect_json_secrets(json.loads(request.body), secrets)
            except ValueError:
                for name, value in parse_qsl(request.body):
                    if is_sensitive_name(name, SENSITIVE_BODY_KEY_PARTS):
                        secrets.add(name, value)
        for text in [request.url, request.body or "", *request.headers.values()]:
            for email in EMAIL_RE.findall(text):
                secrets.add("email", email)
    return secrets


@dataclass
class Request:
    entry: dict
    method: str
    url: str
    headers: dict
    body: str | None
    expected_status: object
    page_no: int
    page_title: str
    separation: float = 0


def _page_index(har):
    return {
        page["id"]: (n, page.get("title", page["id"]))
        for n, page in enumerate(har["log"].get("pages", []), start=1)
    }


def _host_report(entries):
    hosts = Counter(_netloc(e["request"]["url"]) for e in entries if not is_static(e))
    static = sum(1 for e in entries if is_static(e))
    lines = [f"  {n:5d}  {host}" for host, n in hosts.most_common()]
    return hosts, static, "\n".join(lines)


def select_requests(har, hosts, include_static=False):
    """Pick the entries to replay and report what was dropped."""
    entries = _extract_and_sort_requests(har)
    pages = _page_index(har)
    dropped_hosts = Counter()
    dropped_static = 0
    selected = []
    # set_expected_status_code removes redirect targets from entries mid-loop
    for entry in list(entries):
        if not any(entry is e for e in entries):
            continue
        request = entry["request"]
        if not entry["response"]["status"]:
            continue
        if not include_static and is_static(entry):
            dropped_static += 1
            continue
        if not host_allowed(request["url"], hosts):
            dropped_hosts[_netloc(request["url"])] += 1
            continue
        method = request["method"].lower()
        if method not in SUPPORTED_METHODS:
            logger.warning(
                "Skipping unsupported method %s %s", method.upper(), request["url"]
            )
            continue
        post_data = request.get("postData")
        page_no, page_title = pages.get(entry.get("pageref"), (0, ""))
        selected.append(
            Request(
                entry=entry,
                method=method,
                url=request["url"],
                headers=set_request_headers_dict(entry),
                body=post_data.get("text") if post_data else None,
                expected_status=set_expected_status_code(entry, entries),
                page_no=page_no,
                page_title=page_title,
            )
        )
    return selected, dropped_hosts, dropped_static


def _set_separations(requests, separation_s):
    for i, request in enumerate(requests):
        if separation_s:
            request.separation = separation_s
        elif i + 1 < len(requests):
            gap = _started_at(requests[i + 1].entry) - _started_at(request.entry)
            request.separation = round(max(gap.total_seconds(), 0.0), 3)
        else:
            request.separation = 0


def _transaction_name(request, secrets):
    parts = urlsplit(request.url)
    # no query string, so repeated calls aggregate under one name
    target = f"{request.method.upper()} {parts.netloc}{parts.path or '/'}"
    if request.page_no:
        target = f"Page {request.page_no} | {target}"
    return secrets.redact(target)


def _render_headers(headers, secrets):
    if not headers:
        return "{}"
    lines = "".join(
        f"                    {name!r}: {secrets.expression(value)},\n"
        for name, value in headers.items()
    )
    return "{\n" + lines + "                }"


def _render_request(request, secrets):
    body = ""
    if request.body is not None:
        body = f"                data={secrets.expression(request.body)},\n"
    return TEMPLATE.render(
        name=repr(_transaction_name(request, secrets)),
        method=request.method,
        url=secrets.expression(request.url),
        headers=_render_headers(request.headers, secrets),
        body=body,
        expected_status=repr(request.expected_status),
        separation=request.separation,
    )


def _comment_block(lines):
    return "".join(f"# {line}".rstrip() + "\n" for line in lines)


def _render_file(source_name, requests, secrets, dropped_hosts, dropped_static):
    kept_hosts = Counter(_netloc(r.url) for r in requests)
    seconds = round(sum(r.separation for r in requests), 3)
    header = [
        f"Generated by `mite har` from {source_name}.",
        "",
        f"Kept {len(requests)} requests to:",
        *[f"  {host} ({n})" for host, n in kept_hosts.most_common()],
    ]
    if dropped_static:
        header.append(
            f"Dropped {dropped_static} static assets and CORS preflights"
            " (--include-static keeps them)."
        )
    if dropped_hosts:
        header.append(
            f"Dropped {sum(dropped_hosts.values())} requests to hosts not in --host:"
        )
        header += [f"  {host} ({n})" for host, n in dropped_hosts.most_common()]
    header.append("")
    if secrets.keys:
        header.append(
            "Values that looked like credentials or personal data were removed"
        )
        header.append("from the recording. Set them before running:")
        for key in secrets.keys.values():
            header.append(f"  export MITE_CONF_{key}=...")
        header.append(
            "Tokens the application issues during the journey (e.g. at login)"
        )
        header.append("must be set the same way for now.")
        header.append("")
    header += [
        "Run the journey once:",
        "  mite journey test <module>:journey",
        "Run it under load (edit TARGET_TPS and DURATION_S below):",
        "  mite scenario test <module>:scenario",
        "<module> is this file's name without .py; run from its directory.",
    ]

    stdlib = ["import math"]
    if secrets.uses_quote(
        [r.url for r in requests]
        + [r.body or "" for r in requests]
        + [v for r in requests for v in r.headers.values()]
    ):
        stdlib.append("from urllib.parse import quote")
    mite_imports = [
        "from mite import ensure_fixed_separation",
        "from mite.volume_model import Constant",
        "from mite_browser import browser_decorator",
        "from mite_http.checks import check_status_code",
    ]
    if secrets.keys:
        mite_imports.insert(1, "from mite.exceptions import MiteError")

    out = _comment_block(header) + "\n"
    out += "\n".join(stdlib + [""] + mite_imports) + "\n\n\n"
    out += (
        "# Load settings: edit these to change the test.\n"
        "TARGET_TPS = 1  # requests per second across all running journeys\n"
        "DURATION_S = 300\n"
        "\n"
        "# From the recording: one journey makes this many requests and takes at\n"
        "# least this long because of the separations below.\n"
        f"REQUESTS_PER_JOURNEY = {len(requests)}\n"
        f"SECONDS_PER_JOURNEY = {seconds}\n"
        "\n\n"
    )
    if secrets.keys:
        out += (
            "def _config(ctx, key):\n"
            "    value = ctx.config.get(key)\n"
            "    if value is None:\n"
            '        raise MiteError(f"Missing config {key!r}: set MITE_CONF_{key}")\n'
            "    return value\n"
            "\n\n"
        )
    out += "@browser_decorator()\nasync def journey(ctx):\n"
    page_no = None
    for request in requests:
        if request.page_no != page_no:
            page_no = request.page_no
            if page_no:
                out += f"    # Page {page_no}: {secrets.redact(request.page_title)}\n"
            else:
                out += "    # Requests not linked to a page\n"
        out += _render_request(request, secrets)
    out = out.rstrip("\n") + "\n\n\n"
    out += (
        "def scenario():\n"
        "    # Each running journey makes about\n"
        "    # REQUESTS_PER_JOURNEY / SECONDS_PER_JOURNEY requests per second.\n"
        "    # Constant's `tps` is the number of journeys running at once.\n"
        "    journeys = 1\n"
        "    if SECONDS_PER_JOURNEY:\n"
        "        journeys = max(\n"
        "            1, math.ceil(TARGET_TPS * SECONDS_PER_JOURNEY / REQUESTS_PER_JOURNEY)\n"
        "        )\n"
        '    return [[f"{__name__}:journey", None, Constant(duration=DURATION_S, tps=journeys)]]\n'
    )
    return out


def har_convert_to_mite(
    file_name, converted_file_name, separation_s=1, hosts=None, include_static=False
):
    """Convert a HAR file to a mite journey and scenario.

    Only requests to ``hosts`` (glob patterns, e.g. ``*.example.com``) are kept.
    Without ``hosts``, nothing is written and HarConversionError lists the hosts
    in the recording. Each request is wrapped in ensure_fixed_separation:
    ``separation_s`` seconds, or the recorded gap to the next request when 0.
    """
    separation_s = float(separation_s)
    with open(file_name, "r") as f:
        har = json.load(f)
    entries = har["log"]["entries"]
    seen_hosts, static, report = _host_report(entries)
    hint = (
        f"Hosts in {Path(file_name).name} (request counts, {static} static assets"
        f" not counted):\n{report}\n\n"
        "Choose the hosts you want to test, e.g.:\n"
        f"  mite har {file_name} {converted_file_name}"
        + "".join(f" --host={h}" for h, _ in seen_hosts.most_common(1))
    )
    if not hosts:
        raise HarConversionError(f"No --host given; nothing written.\n\n{hint}")

    requests, dropped_hosts, dropped_static = select_requests(
        har, hosts, include_static
    )
    if not requests:
        raise HarConversionError(
            f"No requests matched --host {' '.join(hosts)}; nothing written.\n\n{hint}"
        )
    _set_separations(requests, separation_s)
    secrets = collect_secrets(requests)
    source = _render_file(
        Path(file_name).name, requests, secrets, dropped_hosts, dropped_static
    )
    with open(converted_file_name, "w") as nf:
        nf.write(source)
    return requests
